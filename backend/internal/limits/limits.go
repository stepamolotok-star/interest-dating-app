// Package limits — ограничения против спама и ботов. Обычный человек до них
// не дотягивается; рассылка и автоматические «Интересно» упираются сразу.
package limits

// Пороги. Считаются по базе за скользящее окно, поэтому работают и без Redis.
const (
	// «Интересно» за сутки (лента и «Рядом» вместе).
	LikesPerDay = 200
	// Сообщений в минуту — живой человек столько не печатает.
	MessagesPerMinute = 20
	// Новых разговоров (первых сообщений) за сутки.
	FirstMessagesPerDay = 40
	// Один и тот же текст первым сообщением — не больше стольких людей за сутки.
	SameHelloPerDay = 10
	// Жалоб за сутки от одного человека.
	ReportsPerDay = 20
)

// Error — ограничение сработало. Сообщение показывается человеку как есть.
type Error struct{ Message string }

func (e *Error) Error() string { return e.Message }

var (
	ErrLikes         = &Error{"Слишком много «Интересно» за сутки — продолжить можно завтра. Так мы защищаемся от ботов."}
	ErrTooFast       = &Error{"Вы пишете слишком быстро — подождите минуту."}
	ErrFirstMessages = &Error{"Сегодня вы уже начали много новых разговоров — продолжить можно завтра."}
	ErrSameHello     = &Error{"Похоже на рассылку: этот текст вы уже отправили многим. Напишите человеку что-то своё — например, про ваш общий интерес."}
	ErrReports       = &Error{"Слишком много жалоб за сутки. Если вам угрожают — нажмите «Заблокировать», человек сразу пропадёт."}
)
